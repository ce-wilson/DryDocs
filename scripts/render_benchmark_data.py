"""Regenerate web/src/underhood/benchmarkData.ts from the P0 benchmark run (O31).

TWO INPUTS, ONE RENDER. The MEASUREMENTS come from the evaluation-harness run
``knowledge/upgrade-plans/p0-benchmark/benchmark_p0_results.json`` (chars
retrieved and latency per question per arm, the 2026-07-16 live run). The
VERDICTS — pass / fail / partial / abstain / hallucination per cell, the
qualifiers, the notes, the Cypher snippets shown, the strategy prose, the
corpus tier table — are HUMAN judgments recorded in
``knowledge/upgrade-plans/docmeta-p0-verdict.md`` and held machine-readably in
``knowledge/upgrade-plans/p0-benchmark/verdicts.yaml``. A verdict may OVERRIDE
a measured ``chars`` where the scorer re-scored a cell (three today: the two
"rule only" manifest partials and the correct out-of-scope abstention are
scored at 0 characters because nothing usable was retrieved); each override is
declared on the cell, never hand-carried into the TypeScript.

TOTALS and EFFICIENCY are DERIVED here from those cells — sums of effective
chars, pass counts, harness latency medians, the manifest-vs-traversal ratio —
so the scoreboard can no longer disagree with the rows it summarises. WHAT THE
DERIVATION CHANGED, stated so nobody reads it as drift: the hand-carried totals
were 16,400 / 31,400 / 449,500 chars (27.4x) and a full-text recall of 7/12;
the run's own numbers are 15,354 / 34,195 / 450,550 (29.3x) and the cells the
file itself carried sum to 6/12 for full-text — the old scoreboard disagreed
with its own rows. Totals are TOKEN COST (harness chars, what was read); a
cell's ``chars`` is what was SCORED (the verdict's override where one exists).

Deterministic: same inputs, same bytes, LF. Guarded by
``tests/unit/test_benchmark_data.py`` (committed file == regeneration).
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
RESULTS = REPO / "knowledge" / "upgrade-plans" / "p0-benchmark" / "benchmark_p0_results.json"
VERDICTS = REPO / "knowledge" / "upgrade-plans" / "p0-benchmark" / "verdicts.yaml"
OUT = REPO / "web" / "src" / "underhood" / "benchmarkData.ts"
ARMS = ("traversal", "fulltext", "manifest")


def _ts_str(value: str) -> str:
    """A TypeScript single-quoted string literal."""
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n") + "'"


def _num(n: int) -> str:
    """TS numeric literal with the underscore grouping the file used."""
    return f"{n:_}" if n >= 10_000 else str(n)


def _k(chars: int) -> str:
    return f"~{chars / 4 / 1000:.1f}k"


def build(results: list[dict], verdicts: dict) -> str:
    harness = {e["id"]: e for e in results}
    questions = verdicts["questions"]
    # effective per-cell chars: the verdict override wins when declared
    cells: dict[str, dict[str, dict]] = {}
    for q in questions:
        h = harness[q["id"]]["arms"]
        cells[q["id"]] = {}
        for arm in ARMS:
            v = q[arm]
            chars = v.get("chars_override", h[arm]["chars"])
            ms = round(h[arm]["ms"]) if arm != "manifest" else None
            cells[q["id"]][arm] = {
                "kind": v["kind"],
                "chars": chars,
                "ms": ms,
                "qualifier": v.get("qualifier"),
            }

    def total(arm: str) -> int:
        # TOKEN COST is what was actually read, so totals sum the HARNESS chars —
        # a "rule only" manifest read still cost the whole manifest even though
        # the cell is SCORED at 0 usable characters.
        return sum(harness[q["id"]]["arms"][arm]["chars"] for q in questions)

    def recall(arm: str) -> str:
        kinds = [cells[q["id"]][arm]["kind"] for q in questions]
        passes = sum(1 for k in kinds if k in ("pass", "abstain"))
        partial = sum(1 for k in kinds if k == "partial")
        base = f"{passes}/{len(kinds)}"
        return f"{base} ({partial} partial)" if partial else base

    def median_ms(arm: str) -> int:
        return round(statistics.median(harness[q["id"]]["arms"][arm]["ms"] for q in questions))

    totals = {arm: total(arm) for arm in ARMS}
    ratio = totals["manifest"] / totals["traversal"] if totals["traversal"] else 0.0
    strategies = {s["id"]: s for s in verdicts["strategies"]}

    out: list[str] = []
    w = out.append
    w("// GENERATED by scripts/render_benchmark_data.py — never hand-edit (O31).")
    w("// MEASUREMENTS: knowledge/upgrade-plans/p0-benchmark/benchmark_p0_results.json")
    w("//   (the 2026-07-16 live P0 benchmark run: chars retrieved + latency per cell).")
    w("// VERDICTS: knowledge/upgrade-plans/p0-benchmark/verdicts.yaml — the human")
    w("//   pass/fail/partial/abstain/hallucination judgments, notes and shown Cypher,")
    w("//   transcribed from the verdict record:")
    for ref in verdicts["verdict_record"]:
        w(f"//   {ref}")
    w("// TOTALS and EFFICIENCY are derived from the cells below, never typed.")
    w("//")
    w('// "Under the Hood" (/under-the-hood) renders this as a benchmark showcase —')
    w("// how the DryDocs agent could retrieve knowledge three different ways, and the")
    w("// live test that decided BUILD over shrink-to-registry-only.")
    w("")
    w("export type StrategyId = 'manifest' | 'fulltext' | 'traversal'")
    w("")
    w("export interface StrategyInfo {")
    w("  id: StrategyId")
    w("  label: string")
    w('  /** the mono kicker shown on the strategy card, e.g. "unstructured files" */')
    w("  kicker: string")
    w("  how: string")
    w("  recall: string")
    w("  tokens: string")
    w("  latency: string")
    w("  failureModes: string")
    w("  /** css custom-property token name (no leading `var()`), e.g. '--yellow' */")
    w("  token: string")
    w("}")
    w("")
    w("export const STRATEGIES: readonly StrategyInfo[] = [")
    for arm in ("manifest", "fulltext", "traversal"):
        s = strategies[arm]
        latency = (
            "~instant to route, then whole files to read"
            if arm == "manifest"
            else f"{median_ms(arm)}ms median"
        )
        w("  {")
        w(f"    id: {_ts_str(arm)},")
        w(f"    label: {_ts_str(s['label'])},")
        w(f"    kicker: {_ts_str(s['kicker'])},")
        w(f"    how: {_ts_str(s['how'])},")
        w(f"    recall: {_ts_str(recall(arm))},")
        w(f"    tokens: {_ts_str(f'≈{totals[arm]:,} ch ({_k(totals[arm])} tok)')},")
        w(f"    latency: {_ts_str(latency)},")
        w(f"    failureModes: {_ts_str(s['failureModes'])},")
        w(f"    token: {_ts_str(s['token'])},")
        w("  },")
    w("]")
    w("")
    c = verdicts["corpus"]
    w("export const CORPUS = {")
    w(f"  docCount: {c['docCount']},")
    w(f"  label: {_ts_str(c['label'])},")
    w(f"  totalChars: {_num(c['totalChars'])},")
    w(f"  chunkCount: {c['chunkCount']},")
    w("  tiers: [")
    for t in c["tiers"]:
        w(
            f"    {{ tier: {_ts_str(t['tier'])}, chunks: {t['chunks']}, chars: {_num(t['chars'])}, token: {_ts_str(t['token'])} }},"
        )
    w("  ],")
    w("} as const")
    w("")
    w("export const TOTALS = {")
    w(
        f"  traversal: {{ chars: {_num(totals['traversal'])}, tokens: {_ts_str(_k(totals['traversal']))}, "
        f"recall: {_ts_str(recall('traversal'))}, latencyMedianMs: {median_ms('traversal')} }},"
    )
    w(
        f"  fulltext: {{ chars: {_num(totals['fulltext'])}, tokens: {_ts_str(_k(totals['fulltext']))}, "
        f"recall: {_ts_str(recall('fulltext'))}, latencyMedianMs: {median_ms('fulltext')} }},"
    )
    w(
        f"  manifest: {{ chars: {_num(totals['manifest'])}, tokens: {_ts_str(_k(totals['manifest']))}, "
        f"recall: {_ts_str(recall('manifest'))}, latencyLabel: 'routing ~instant' }},"
    )
    w("} as const")
    w("")
    per_q = [
        harness[q["id"]]["arms"]["manifest"]["chars"]
        / harness[q["id"]]["arms"]["traversal"]["chars"]
        for q in questions
        if harness[q["id"]]["arms"]["traversal"]["chars"]
        > 2  # the 2-char empty-result rows are not a ratio
        and harness[q["id"]]["arms"]["manifest"]["chars"]
    ]
    w("export const EFFICIENCY = {")
    w(f"  headline: {_ts_str(f'{ratio:.1f}×')},")  # noqa: RUF001 — the × is the UI glyph
    w("  label: 'manifest-vs-traversal token efficiency',")
    w(f"  perQuestionRange: {_ts_str(f'{min(per_q):.0f}×–{max(per_q):.0f}×')},")  # noqa: RUF001
    w("} as const")
    w("")
    w("export type ResultKind = 'pass' | 'fail' | 'partial' | 'abstain' | 'hallucination'")
    w("")
    w("export interface StrategyResult {")
    w("  kind: ResultKind")
    w("  /** characters retrieved/ingested for this question, this strategy */")
    w("  chars: number")
    w("  ms?: number")
    w('  /** e.g. "informed" — naive phrasing failed, domain-mapped terms succeeded */')
    w("  qualifier?: string")
    w("}")
    w("")
    w("export type QuestionClass =")
    classes = list(verdicts["class_token"].keys())
    for cls in classes:
        w(f"  | {_ts_str(cls)}")
    w("")
    w("export const CLASS_TOKEN: Record<QuestionClass, string> = {")
    for cls, tok in verdicts["class_token"].items():
        key = (
            cls
            if cls.replace("-", "").replace("/", "").isalnum()
            and "/" not in cls
            and "-" not in cls
            and " " not in cls
            else _ts_str(cls)
        )
        w(f"  {key}: {_ts_str(tok)},")
    w("}")
    w("")
    w("export interface CypherSnippet {")
    w("  label: string")
    w("  code: string")
    w("}")
    w("")
    w("export interface BenchmarkQuestion {")
    w("  id: string")
    w("  cls: QuestionClass")
    w("  text: string")
    w("  traversal: StrategyResult")
    w("  fulltext: StrategyResult")
    w("  manifest: StrategyResult")
    w("  note: string")
    w("  cypher?: readonly CypherSnippet[]")
    w("}")
    w("")
    w("export const QUESTIONS: readonly BenchmarkQuestion[] = [")
    for q in questions:
        w("  {")
        w(f"    id: {_ts_str(q['id'])},")
        w(f"    cls: {_ts_str(q['cls'])},")
        w(f"    text: {_ts_str(harness[q['id']]['q'])},")
        for arm in ARMS:
            cell = cells[q["id"]][arm]
            parts = [f"kind: {_ts_str(cell['kind'])}", f"chars: {_num(cell['chars'])}"]
            if cell["ms"] is not None:
                parts.append(f"ms: {cell['ms']}")
            if cell["qualifier"]:
                parts.append(f"qualifier: {_ts_str(cell['qualifier'])}")
            w(f"    {arm}: {{ {', '.join(parts)} }},")
        w(f"    note: {_ts_str(q['note'])},")
        if q.get("cypher"):
            w("    cypher: [")
            for snip in q["cypher"]:
                w("      {")
                w(f"        label: {_ts_str(snip['label'])},")
                w(f"        code: {_ts_str(snip['code'])},")
                w("      },")
            w("    ],")
        w("  },")
    w("]")
    w("")
    w("export const PROVENANCE_LINE =")
    w(
        "  'Live benchmark 2026-07-16 · measurements: knowledge/upgrade-plans/p0-benchmark/"
        "benchmark_p0_results.json · ' +"
    )
    w("  'verdicts: knowledge/upgrade-plans/docmeta-p0-verdict.md · explainer: ' +")
    w(
        "  'docs/design/graph-retrieval-benchmark-explainer.md · regenerated by "
        "scripts/render_benchmark_data.py'"
    )
    return "\n".join(out) + "\n"


def main() -> int:
    results = json.loads(RESULTS.read_text(encoding="utf-8"))
    verdicts = yaml.safe_load(VERDICTS.read_text(encoding="utf-8"))
    OUT.write_text(build(results, verdicts), encoding="utf-8", newline="\n")
    print(
        f"wrote {OUT} ({len(verdicts['questions'])} questions from {RESULTS.name} + {VERDICTS.name})"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
