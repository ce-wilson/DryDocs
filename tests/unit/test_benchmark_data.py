"""O31 — web/src/underhood/benchmarkData.ts is a RENDER of the P0 harness run +
the verdict ledger, never hand-carried: committed file == regeneration."""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
SCRIPT = REPO / "scripts" / "render_benchmark_data.py"


def _mod():
    spec = importlib.util.spec_from_file_location("render_benchmark_data", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["render_benchmark_data"] = mod
    spec.loader.exec_module(mod)
    return mod


def test_committed_benchmark_data_matches_regeneration() -> None:
    m = _mod()
    results = json.loads(m.RESULTS.read_text(encoding="utf-8"))
    verdicts = yaml.safe_load(m.VERDICTS.read_text(encoding="utf-8"))
    assert m.OUT.read_text(encoding="utf-8") == m.build(
        results, verdicts
    ), "benchmarkData.ts is stale — run `poetry run python scripts/render_benchmark_data.py`"


def test_every_question_in_the_run_has_a_verdict_and_vice_versa() -> None:
    m = _mod()
    run_ids = [e["id"] for e in json.loads(m.RESULTS.read_text(encoding="utf-8"))]
    verdict_ids = [
        q["id"] for q in yaml.safe_load(m.VERDICTS.read_text(encoding="utf-8"))["questions"]
    ]
    assert run_ids == verdict_ids


def test_totals_are_derived_from_the_cells_not_typed() -> None:
    """The old file said full-text recall 7/12 while its own rows summed to 6 —
    the derived scoreboard cannot disagree with its rows."""
    m = _mod()
    text = m.OUT.read_text(encoding="utf-8")
    verdicts = yaml.safe_load(m.VERDICTS.read_text(encoding="utf-8"))
    passes = sum(1 for q in verdicts["questions"] if q["fulltext"]["kind"] in ("pass", "abstain"))
    assert f"recall: '{passes}/12'" in text
    assert "GENERATED by scripts/render_benchmark_data.py" in text
